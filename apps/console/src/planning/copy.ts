export function tabLabel(l: Locale, key: string, ko: string) {
  return l === "ko"
    ? ko
    : l === "ar"
      ? (arabicTabs[key] ?? key)
      : key
          .split("-")
          .map((x) => x[0].toUpperCase() + x.slice(1))
          .join(" ");
}
