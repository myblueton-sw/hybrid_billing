const {chromium}=require(process.env.HB_PLAYWRIGHT_MODULE||'playwright');
const fs=require('fs'),path=require('path'),{execFileSync}=require('child_process');
const root=path.resolve(__dirname,'../../../..');
const out=path.join(root,'output/designs/HB-38');
fs.mkdirSync(out,{recursive:true});
fs.mkdirSync(path.join(root,'output/pdf'),{recursive:true});
const assert=(x,m)=>{if(!x)throw Error(m);};
(async()=>{
 const browser=await chromium.launch({headless:true,executablePath:process.env.HB_CHROMIUM_PATH||undefined});
 const report=[];
 for(const lang of ['en','ko']){
  const page=await browser.newPage({viewport:{width:1440,height:1200}});
  const errors=[],external=[];
  page.on('pageerror',e=>errors.push(String(e)));
  page.on('request',r=>{if(/^https?:/.test(r.url()))external.push(r.url());});
  const url='file://'+path.join(__dirname,'index.html')+'?lang='+lang;
  const go=async route=>{await page.goto(url+'#'+route);};
  const routes=['operations','detail/C00226','policies','oci','preview','history'];
  const pages=[];
  for(let i=0;i<routes.length;i++){
   await go(routes[i]);
   await page.screenshot({path:path.join(out,`${lang}-${i+1}.png`),fullPage:true});
   await page.emulateMedia({media:'print'});
   const bounds=await page.evaluate(()=>({bottom:document.querySelector('#content').getBoundingClientRect().bottom,footer:document.querySelector('footer').getBoundingClientRect().top,overflow:document.documentElement.scrollWidth>innerWidth}));
   assert(!bounds.overflow&&bounds.bottom<bounds.footer,`Print overflow ${lang} ${routes[i]} ${JSON.stringify(bounds)}`);
   const pdf=path.join(out,`${lang}-${i+1}.pdf`);
   await page.pdf({path:pdf,preferCSSPageSize:true,printBackground:true});
   assert(/Pages:\s+1\s/.test(execFileSync('pdfinfo',[pdf],{encoding:'utf8'})),`Unexpected page count ${pdf}`);
   pages.push(pdf);report.push({lang,route:routes[i],bounds});
   await page.emulateMedia({media:'screen'});
  }
  const final=path.join(root,'output/pdf',`hybrid-billing-operations-contracts-v6${lang==='ko'?'-ko':''}.pdf`);
  execFileSync('pdfunite',[...pages,final]);
  await go('operations');
  assert(await page.locator('tbody tr').count()===25,'Default pagination');
  assert((await page.locator('.metrics').innerText()).includes('5,000'),'Whole-month target count');
  await page.locator('#size').selectOption('100');
  assert(await page.locator('tbody tr').count()===100,'100-row page');
  await page.locator('#next').click();
  assert(await page.evaluate(()=>hb38.state.page)===2,'Next page');
  const first=await page.locator('tbody a').first().getAttribute('href');
  await page.locator('tbody a').first().click();
  assert((await page.locator('h1').innerText()).length>0,'Detail opens');
  await page.locator('.back').click();
  await page.locator('#result-count').waitFor();
  assert(await page.evaluate(()=>hb38.state.page)===2,'Detail return page preserved');
  assert(await page.evaluate(()=>document.activeElement.getAttribute('href'))===first,'Detail return focus');
  await page.locator('#search').fill('C00226');
  assert(await page.locator('tbody tr').count()===1,'Company identity filter');
  assert((await page.locator('.metrics').innerText()).includes('5,000'),'Filter mutated whole month count');
  await page.locator('#search').fill('does-not-exist');
  assert(await page.locator('.empty').count()===1,'No-match state');
  await page.locator('#search').fill('');
  await page.locator('summary').click();
  await page.locator('#reason').selectOption('unknown');
  assert(await page.evaluate(()=>hb38.filtered().length)===15,'Unknown outcome count');
  await page.locator('tbody a').first().click();
  await page.locator('.back').waitFor();
  assert((await page.locator('#content').innerText()).includes(lang==='ko'?'재발행하지':'No reissue'),'Unknown safe action');
  await go('operations');
  await page.locator('[data-tab="exceptions"]').click();
  assert(await page.evaluate(()=>hb38.filtered().length)===115,'Exception subset count');
  assert(await page.evaluate(()=>hb38.filtered().every(r=>!r.reason)),'Issued exception subset');
  await page.locator('#month').selectOption('2026-08');
  assert((await page.locator('.metrics').innerText()).includes(lang==='ko'?'미조회':'Not loaded'),'Unknown month represented as zero');
  await page.locator('#month').selectOption('2026-09');
  await page.locator('[data-tab="all"]').click();
  await page.locator('#mode').selectOption('single');
  assert(await page.evaluate(()=>hb38.filtered().length)===1,'Single-company mode');
  await go('detail/C00001');
  await page.locator('#mode').selectOption('single');
  await page.waitForFunction(()=>location.hash==='#detail/C00226');
  assert((await page.locator('#content').innerText()).includes('C00226'),'Workspace detail identity');
  await page.locator('a[href="#history"]').first().click();
  await page.waitForFunction(()=>document.querySelector('.eyebrow')?.textContent.includes('C00226'));
  await go('detail/bad-id');
  assert((await page.locator('h1').innerText()).includes(lang==='ko'?'찾을':'not found'),'Unknown customer mapped incorrectly');
  await page.setViewportSize({width:390,height:844});
  for(const route of ['operations','detail/C00226','policies','oci','preview','history']){
   await go(route);
   assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'Mobile overflow '+route);
   await page.screenshot({path:path.join(out,`${lang}-${route.split('/')[0]}-mobile.png`),fullPage:true});
  }
  assert(errors.length===0&&external.length===0,'Browser errors/network '+JSON.stringify({errors,external}));
  report.push({lang,errors,external,checks:'pagination 25/100; filters; preserved count/page/focus; unknown outcome; issued exception subset; unavailable month; single company; unknown identity; mobile width'});
  await page.close();
 }
 fs.writeFileSync(path.join(out,'verification.json'),JSON.stringify(report,null,2));
 await browser.close();console.log(JSON.stringify({locales:2,pagesPerPdf:6,report:path.join(out,'verification.json')}));
})().catch(e=>{console.error(e);process.exit(1);});
